#!/usr/bin/env python3
"""Fetch InSight Marsquake Catalog from IRIS and upload to HF.

Source: IRIS Mars Event Service — the official distribution point for the
InSight Marsquake Service (MQS) catalog (final v14 release, mission ended Dec 2022).
"""

import io

import pandas as pd
import requests

from hf_dataset_utils import Pipeline

IRIS_URL = "http://service.iris.edu/irisws/mars-event/1/query"
HF_REPO = "juliensimon/insight-marsquake-catalog"

# Event type classification hierarchy (MQS quality tiers)
EVENT_TYPE_TIERS = {
    "LOW_FREQUENCY": "LF",
    "BROADBAND": "BB",
    "2.4_HZ": "2.4Hz",
    "HIGH_FREQUENCY": "HF",
    "VERY_HIGH_FREQUENCY": "VF",
    "SUPER_HIGH_FREQUENCY": "SF",
}

# ── Column descriptions for README schema table ─────────────────────
COLUMN_DESCRIPTIONS = {
    "event_id": "IRIS-assigned event identifier (e.g. 'mqs2022wrzi'); unique key for each marsquake detection in the MQS catalog",
    "event_time": "Origin time of the seismic event (UTC); InSight's SEIS seismometer operated Nov 2018 to Dec 2022, spanning over 1,400 sols on Mars",
    "latitude": "Estimated epicentral latitude on Mars (degrees, -90 to +90); null for most events because InSight was a single-station network and location requires surface wave or polarization analysis",
    "longitude": "Estimated epicentral longitude on Mars (degrees, east-positive 0-360); null if location could not be determined from single-station analysis",
    "depth_km": "Estimated source depth in km; null if undetermined; LF events typically 20-50 km depth, HF events typically <10 km in the shallow crust",
    "author": "Name or team identifier of the analyst who determined the event origin solution (typically the MQS team at ETH Zurich)",
    "catalog": "MQS catalog version identifier (e.g. 'InSight_MQS_public_v14'); v14 is the final release after mission end",
    "contributor": "Institution or agency that contributed the event solution (e.g. 'MQS' for InSight MarsQuake Service run by ETH Zurich/IPGP)",
    "contributor_id": "MQS sol-based event designation (e.g. 'S0173a' = sol 173, first event of the day; S=seismic, sol number, letter suffix for ordering)",
    "mag_type": "Magnitude scale used: 'MW' = moment magnitude (preferred for LF/BB events), 'MbS' = body-wave magnitude for Mars, 'MFB' = frequency-band magnitude",
    "magnitude": "Event magnitude on the specified scale; InSight detected events ranging from ~0.5 to 4.7 M_w; the largest event (sol 1222) produced surface waves circling Mars",
    "mag_author": "Name or team identifier of the analyst who determined the magnitude estimate",
    "event_location_name": "Named Martian region near the estimated epicenter (e.g. 'Cerberus Fossae', 'Elysium Southwest'); null if location undetermined; most located events cluster near Cerberus Fossae",
    "event_type": "MQS event type classification: LOW_FREQUENCY (deep tectonic, clear P+S waves), BROADBAND (intermediate depth), HIGH_FREQUENCY (shallow crustal), VERY_HIGH_FREQUENCY (very shallow), SUPER_HIGH_FREQUENCY (near-surface thermal cracking), 2.4_HZ (characteristic spectral resonance of debated origin)",
    "event_type_short": "Abbreviated event type: LF, BB, HF, VF, SF, or 2.4Hz; derived from event_type for convenience",
}

# ── Dataset description ──────────────────────────────────────────────
DESCRIPTION = """\
Complete catalog of marsquakes detected by NASA InSight's SEIS seismometer on Mars, \
sourced from the IRIS Mars Event Service. The InSight mission operated from November 2018 \
to December 2022, deploying the first seismometer successfully placed on another planet.

Over the course of the mission, SEIS detected over 1,300 marsquakes, revealing the internal \
structure of Mars for the first time. Analysis of the marsquake catalog revealed that Mars has \
a relatively thick crust (24-72 km), a mantle with a lithosphere extending to roughly 500 km \
depth, and a liquid iron-alloy core with a radius of approximately 1,830 km -- larger and less \
dense than previously expected.

The event type classifications reflect distinct seismic source mechanisms on Mars. Low-frequency \
(LF) and broadband (BB) events are analogous to tectonic earthquakes, generated by stress release \
along faults, and tend to originate in the Cerberus Fossae region. High-frequency (HF), \
very-high-frequency (VF), and super-high-frequency (SF) events originate in the shallow crust \
and may include thermal cracking. The temporal distribution shows strong seasonal modulation, \
with higher detection rates during northern hemisphere winter when wind noise was lowest. The \
largest event -- a magnitude 4.7 marsquake on sol 1222 (May 4, 2022) -- produced surface waves \
that circled the planet multiple times.
"""


def main():
    print("Fetching InSight marsquake catalog from IRIS...")
    resp = requests.get(IRIS_URL, params={"format": "text"}, timeout=60)
    resp.raise_for_status()

    # Parse pipe-separated text
    df = pd.read_csv(io.StringIO(resp.text), sep="|", dtype=str)

    # Strip whitespace from column names and all string values
    df.columns = df.columns.str.strip()
    for col in df.select_dtypes(include=["object"]).columns:
        df[col] = df[col].str.strip()

    print(f"  {len(df):,} events fetched, {len(df.columns)} columns")

    # snake_case column names
    df.columns = (
        df.columns.str.lower()
        .str.replace(r"[^a-z0-9]+", "_", regex=True)
        .str.strip("_")
    )

    # Rename for clarity
    df = df.rename(columns={
        "eventid": "event_id",
        "time": "event_time",
        "contributorid": "contributor_id",
        "magtype": "mag_type",
        "magauthor": "mag_author",
        "eventlocationname": "event_location_name",
        "eventtype": "event_type",
    })

    # Parse datetime
    if "event_time" in df.columns:
        df["event_time"] = pd.to_datetime(df["event_time"], errors="coerce")

    # Derived column: short event type label
    if "event_type" in df.columns:
        df["event_type_short"] = df["event_type"].map(EVENT_TYPE_TIERS)

    # Keep only described columns
    df = df[[c for c in df.columns if c in COLUMN_DESCRIPTIONS]]

    # Sort by event time
    if "event_time" in df.columns:
        df = df.sort_values("event_time", ascending=True).reset_index(drop=True)

    print(f"  {len(df):,} marsquakes total")

    # ── Domain-specific stats ────────────────────────────────────────
    n_total = len(df)
    n_with_magnitude = int(df["magnitude"].notna().sum())
    n_with_location = int(
        (df["latitude"].notna() & df["longitude"].notna()).sum()
    )

    if "event_time" in df.columns:
        date_min = df["event_time"].min()
        date_max = df["event_time"].max()
        date_range = f"{date_min:%Y-%m-%d} to {date_max:%Y-%m-%d}"
    else:
        date_range = "N/A"

    n_types = df["event_type"].nunique() if "event_type" in df.columns else 0

    # Strongest event
    mag_valid = df[df["magnitude"].notna()]
    if len(mag_valid) > 0:
        strongest_idx = mag_valid["magnitude"].idxmax()
        strongest_id = df.loc[strongest_idx, "event_id"]
        strongest_mag = df.loc[strongest_idx, "magnitude"]
        strongest_line = f"\n- Strongest event: **{strongest_id}** (magnitude {strongest_mag})"
    else:
        strongest_line = ""

    quick_stats = f"""\
- **{n_total:,}** seismic events
- **{n_with_magnitude:,}** with magnitude estimates
- **{n_with_location:,}** with location estimates
- **{n_types}** distinct event type classifications
- Date range: **{date_range}**{strongest_line}"""

    usage = """\
```python
from datasets import load_dataset

ds = load_dataset("juliensimon/insight-marsquake-catalog", split="train")
df = ds.to_pandas()

# Events with known locations
located = df[df["latitude"].notna()]
print(f"{len(located):,} events with determined locations")

# Strongest marsquakes
strongest = df.nlargest(10, "magnitude")[["event_time", "magnitude", "event_type", "latitude", "longitude"]]

# Events by type
import matplotlib.pyplot as plt
type_counts = df["event_type_short"].value_counts()
type_counts.plot(kind="bar")
plt.title("InSight Marsquakes by Event Type")
plt.ylabel("Count")
plt.tight_layout()
plt.show()
```"""

    with Pipeline(
        repo=HF_REPO,
        pretty_name="InSight Marsquake Catalog",
        description=DESCRIPTION,
        tags=["space", "mars", "insight", "marsquake", "seismology", "nasa",
              "planetary-science", "open-data", "tabular-data", "parquet"],
        source_url="http://service.iris.edu/irisws/mars-event/1/",
        task_categories=["tabular-classification"],
        collection_url="https://huggingface.co/collections/juliensimon/space-probe-and-mission-datasets-69c3fe82d410a42b1e313167",
        banner={
            "url": "https://images-assets.nasa.gov/image/PIA24309/PIA24309~small.jpg",
            "alt": "Exploring Jezero Crater on Mars (illustration)",
            "credit": "NASA/JPL-Caltech",
        },
        related_datasets=[
            "juliensimon/mars-craters-robbins",
            "juliensimon/mars-chemcam-compositions",
            "juliensimon/mars-perseverance-weather",
            "juliensimon/deep-space-probes",
        ],
    ) as p:
        df = p.clean(
            df,
            numeric=["latitude", "longitude", "depth_km", "magnitude"],
        )
        p.publish(
            df,
            filename="insight_marsquakes.parquet",
            min_rows=500,
            expected_columns=["event_id", "event_time", "latitude", "longitude",
                              "magnitude", "event_type"],
            critical_columns=["event_id", "event_time"],
            column_descriptions=COLUMN_DESCRIPTIONS,
            quick_stats=quick_stats,
            usage=usage,
            commit_message=f"Update InSight marsquake catalog: {n_total:,} events",
        )
    print("Done.")


if __name__ == "__main__":
    main()
